def train_mean_model(
    x: np.ndarray,
    y: np.ndarray,
    cfg: Config,
) -> MeanMLP:
    model = MeanMLP(cfg.input_dim, cfg.hidden_dim, cfg.feature_dim).to(DEVICE)

    x_t = to_tensor(x)
    y_t = to_tensor(y)
    train_idx, val_idx = train_validation_split(len(x), cfg.validation_fraction)
    train_idx_t = torch.tensor(train_idx, dtype=torch.long, device=DEVICE)
    val_idx_t = torch.tensor(val_idx, dtype=torch.long, device=DEVICE)

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=cfg.learning_rate,
        weight_decay=cfg.weight_decay,
    )

    best_state = None
    best_val = float("inf")
    wait = 0

    for _ in range(cfg.max_epochs):
        model.train()
        optimizer.zero_grad()
        pred = model(x_t[train_idx_t])
        loss = torch.mean((pred - y_t[train_idx_t]) ** 2)
        loss.backward()
        optimizer.step()

        model.eval()
        with torch.no_grad():
            val_pred = model(x_t[val_idx_t])
            val_loss = torch.mean((val_pred - y_t[val_idx_t]) ** 2).item()

        if val_loss < best_val - cfg.min_delta:
            best_val = val_loss
            best_state = {
                key: value.detach().cpu().clone()
                for key, value in model.state_dict().items()
            }
            wait = 0
        else:
            wait += 1

        if wait >= cfg.patience:
            break

    if best_state is not None:
        model.load_state_dict(best_state)

    return model


def train_hetero_model(
    x: np.ndarray,
    y: np.ndarray,
    cfg: Config,
) -> HeteroMLP:
    model = HeteroMLP(
        cfg.input_dim,
        cfg.hidden_dim,
        cfg.feature_dim,
        cfg.variance_floor,
    ).to(DEVICE)

    x_t = to_tensor(x)
    y_t = to_tensor(y)
    train_idx, val_idx = train_validation_split(len(x), cfg.validation_fraction)
    train_idx_t = torch.tensor(train_idx, dtype=torch.long, device=DEVICE)
    val_idx_t = torch.tensor(val_idx, dtype=torch.long, device=DEVICE)

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=cfg.learning_rate,
        weight_decay=cfg.weight_decay,
    )

    best_state = None
    best_val = float("inf")
    wait = 0

    for _ in range(cfg.max_epochs):
        model.train()
        optimizer.zero_grad()

        mu, h2, _ = model(x_t[train_idx_t])
        residual2 = (y_t[train_idx_t] - mu) ** 2
        loss = 0.5 * torch.mean(residual2 / h2 + torch.log(h2))
        loss.backward()
        optimizer.step()

        model.eval()
        with torch.no_grad():
            val_mu, val_h2, _ = model(x_t[val_idx_t])
            val_residual2 = (y_t[val_idx_t] - val_mu) ** 2
            val_loss = 0.5 * torch.mean(
                val_residual2 / val_h2 + torch.log(val_h2)
            ).item()

        if val_loss < best_val - cfg.min_delta:
            best_val = val_loss
            best_state = {
                key: value.detach().cpu().clone()
                for key, value in model.state_dict().items()
            }
            wait = 0
        else:
            wait += 1

        if wait >= cfg.patience:
            break

    if best_state is not None:
        model.load_state_dict(best_state)

    return model


def pinball_loss(y: torch.Tensor, q: torch.Tensor, tau: float) -> torch.Tensor:
    diff = y - q
    return torch.mean(torch.maximum(tau * diff, (tau - 1.0) * diff))


def train_quantile_model(
    x: np.ndarray,
    y: np.ndarray,
    cfg: Config,
) -> QuantileDropoutMLP:
    model = QuantileDropoutMLP(
        cfg.input_dim,
        cfg.hidden_dim,
        cfg.feature_dim,
        cfg.quantile_dropout,
    ).to(DEVICE)

    x_t = to_tensor(x)
    y_t = to_tensor(y)
    train_idx, val_idx = train_validation_split(len(x), cfg.validation_fraction)
    train_idx_t = torch.tensor(train_idx, dtype=torch.long, device=DEVICE)
    val_idx_t = torch.tensor(val_idx, dtype=torch.long, device=DEVICE)

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=cfg.learning_rate,
        weight_decay=cfg.weight_decay,
    )

    tau_lo = cfg.alpha / 2.0
    tau_hi = 1.0 - cfg.alpha / 2.0

    best_state = None
    best_val = float("inf")
    wait = 0

    for _ in range(cfg.max_epochs):
        model.train()
        optimizer.zero_grad()

        qlo_raw, qhi_raw = model.forward_raw(x_t[train_idx_t])
        crossing = torch.mean(F.relu(qlo_raw - qhi_raw))
        loss = (
            pinball_loss(y_t[train_idx_t], qlo_raw, tau_lo)
            + pinball_loss(y_t[train_idx_t], qhi_raw, tau_hi)
            + 0.1 * crossing
        )
        loss.backward()
        optimizer.step()

        model.eval()
        with torch.no_grad():
            val_qlo_raw, val_qhi_raw = model.forward_raw(x_t[val_idx_t])
            val_crossing = torch.mean(F.relu(val_qlo_raw - val_qhi_raw))
            val_loss = (
                pinball_loss(y_t[val_idx_t], val_qlo_raw, tau_lo)
                + pinball_loss(y_t[val_idx_t], val_qhi_raw, tau_hi)
                + 0.1 * val_crossing
            ).item()

        if val_loss < best_val - cfg.min_delta:
            best_val = val_loss
            best_state = {
                key: value.detach().cpu().clone()
                for key, value in model.state_dict().items()
            }
            wait = 0
        else:
            wait += 1

        if wait >= cfg.patience:
            break

    if best_state is not None:
        model.load_state_dict(best_state)

    return model


def train_score_distribution_model(
    x: np.ndarray,
    log_score: np.ndarray,
    cfg: Config,
) -> ScoreDistributionMLP:
    model = ScoreDistributionMLP(
        cfg.input_dim,
        cfg.hidden_dim,
        cfg.epic_dropout,
        cfg.epic_components,
    ).to(DEVICE)

    x_t = to_tensor(x)
    score_t = to_tensor(log_score)
    train_idx, val_idx = train_validation_split(len(x), cfg.validation_fraction)
    train_idx_t = torch.tensor(train_idx, dtype=torch.long, device=DEVICE)
    val_idx_t = torch.tensor(val_idx, dtype=torch.long, device=DEVICE)

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=cfg.learning_rate,
        weight_decay=cfg.weight_decay,
    )

    best_state = None
    best_val = float("inf")
    wait = 0

    for _ in range(cfg.max_epochs):
        model.train()
        optimizer.zero_grad()
        logits, loc, scale = model(x_t[train_idx_t])
        target = score_t[train_idx_t].expand_as(loc)
        standardized = (target - loc) / scale
        component_log_prob = (
            -0.5 * standardized ** 2
            - torch.log(scale)
            - 0.5 * math.log(2.0 * math.pi)
            + F.log_softmax(logits, dim=-1)
        )
        loss = -torch.mean(torch.logsumexp(component_log_prob, dim=-1))
        loss.backward()
        optimizer.step()

        model.eval()
        with torch.no_grad():
            val_logits, val_loc, val_scale = model(x_t[val_idx_t])
            val_target = score_t[val_idx_t].expand_as(val_loc)
            val_standardized = (val_target - val_loc) / val_scale
            val_component_log_prob = (
                -0.5 * val_standardized ** 2
                - torch.log(val_scale)
                - 0.5 * math.log(2.0 * math.pi)
                + F.log_softmax(val_logits, dim=-1)
            )
            val_loss = -torch.mean(
                torch.logsumexp(val_component_log_prob, dim=-1)
            ).item()

        if val_loss < best_val - cfg.min_delta:
            best_val = val_loss
            best_state = {
                key: value.detach().cpu().clone()
                for key, value in model.state_dict().items()
            }
            wait = 0
        else:
            wait += 1

        if wait >= cfg.patience:
            break

    if best_state is not None:
        model.load_state_dict(best_state)

    return model


