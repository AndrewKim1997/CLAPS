def run_split_cp(
    model: MeanMLP,
    data: Dict[str, np.ndarray],
    cfg: Config,
) -> Tuple[np.ndarray, np.ndarray]:
    mu_cal = predict_mean(model, data["x_cal"])
    mu_test = predict_mean(model, data["x_test"])

    scores = np.abs(data["y_cal_std"] - mu_cal)
    qhat = finite_sample_quantile(scores, cfg.alpha)

    lower_std = mu_test - qhat
    upper_std = mu_test + qhat

    return (
        unstandardize_y(lower_std, data["y_mean"], data["y_scale"]),
        unstandardize_y(upper_std, data["y_mean"], data["y_scale"]),
    )


def run_cv_plus(
    data: Dict[str, np.ndarray],
    cfg: Config,
    seed: int,
) -> Tuple[np.ndarray, np.ndarray]:
    """CV+ with the original training set shared across all fold models.

    The calibration sample is partitioned into folds. Each fold model is
    trained on the complete original training set together with the
    calibration observations outside the held-out fold. Residuals are
    evaluated on the held-out calibration fold, whose distribution matches
    the test distribution.
    """
    x_train = data["x_train"]
    y_train_std = data["y_train_std"]
    x_cal = data["x_cal"]
    y_cal_std = data["y_cal_std"]

    n_splits = min(cfg.cv_folds, len(x_cal))
    if n_splits < 2:
        raise ValueError("CV+ requires at least two calibration folds.")

    kf = KFold(
        n_splits=n_splits,
        shuffle=True,
        random_state=10_000 + seed,
    )

    fold_ids = np.empty(len(x_cal), dtype=int)
    residuals = np.empty(len(x_cal), dtype=np.float32)
    test_predictions = []

    for fold_id, (cal_fit_idx, cal_holdout_idx) in enumerate(kf.split(x_cal)):
        # A fold-specific seed makes every CV+ model reproducible.
        set_seed(50_000 + 100 * seed + fold_id)

        x_fit = np.concatenate(
            [x_train, x_cal[cal_fit_idx]],
            axis=0,
        )
        y_fit_std = np.concatenate(
            [y_train_std, y_cal_std[cal_fit_idx]],
            axis=0,
        )

        fold_model = train_mean_model(
            x_fit,
            y_fit_std,
            cfg,
        )

        holdout_pred = predict_mean(
            fold_model,
            x_cal[cal_holdout_idx],
        ).reshape(-1)

        residuals[cal_holdout_idx] = np.abs(
            y_cal_std[cal_holdout_idx].reshape(-1)
            - holdout_pred
        )
        fold_ids[cal_holdout_idx] = fold_id

        test_predictions.append(
            predict_mean(
                fold_model,
                data["x_test"],
            ).reshape(-1)
        )

        del fold_model, x_fit, y_fit_std
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    test_predictions = np.stack(
        test_predictions,
        axis=0,
    )

    # Each held-out calibration observation is paired with the test
    # prediction from the fold model that excluded that observation.
    prediction_for_point = test_predictions[fold_ids, :]

    lower_candidates = (
        prediction_for_point
        - residuals[:, None]
    )
    upper_candidates = (
        prediction_for_point
        + residuals[:, None]
    )

    lower_std = lower_cv_quantile(
        lower_candidates,
        cfg.alpha,
    ).reshape(-1, 1)
    upper_std = upper_cv_quantile(
        upper_candidates,
        cfg.alpha,
    ).reshape(-1, 1)

    return (
        unstandardize_y(
            lower_std,
            data["y_mean"],
            data["y_scale"],
        ),
        unstandardize_y(
            upper_std,
            data["y_mean"],
            data["y_scale"],
        ),
    )


def run_lacp(
    model: HeteroMLP,
    data: Dict[str, np.ndarray],
    cfg: Config,
) -> Tuple[np.ndarray, np.ndarray]:
    mu_cal, h2_cal, _ = predict_hetero(model, data["x_cal"])
    mu_test, h2_test, _ = predict_hetero(model, data["x_test"])

    h_cal = np.sqrt(np.maximum(h2_cal, cfg.variance_floor))
    h_test = np.sqrt(np.maximum(h2_test, cfg.variance_floor))

    scores = np.abs(data["y_cal_std"] - mu_cal) / h_cal
    qhat = finite_sample_quantile(scores, cfg.alpha)

    lower_std = mu_test - qhat * h_test
    upper_std = mu_test + qhat * h_test

    return (
        unstandardize_y(lower_std, data["y_mean"], data["y_scale"]),
        unstandardize_y(upper_std, data["y_mean"], data["y_scale"]),
    )


def run_cqr(
    model: QuantileDropoutMLP,
    data: Dict[str, np.ndarray],
    cfg: Config,
) -> Tuple[np.ndarray, np.ndarray]:
    qlo_cal, qhi_cal = predict_quantiles(model, data["x_cal"])
    qlo_test, qhi_test = predict_quantiles(model, data["x_test"])

    scores = np.maximum(
        qlo_cal - data["y_cal_std"],
        data["y_cal_std"] - qhi_cal,
    )
    qhat = finite_sample_quantile(scores, cfg.alpha)

    lower_std = qlo_test - qhat
    upper_std = qhi_test + qhat
    lower_std, upper_std = order_interval(lower_std, upper_std)

    return (
        unstandardize_y(lower_std, data["y_mean"], data["y_scale"]),
        unstandardize_y(upper_std, data["y_mean"], data["y_scale"]),
    )


def run_uacqr_s(
    model: QuantileDropoutMLP,
    data: Dict[str, np.ndarray],
    cfg: Config,
) -> Tuple[np.ndarray, np.ndarray]:
    # Deterministic quantile estimates form the aleatoric base interval.
    qlo_cal, qhi_cal = predict_quantiles(model, data["x_cal"])
    qlo_test, qhi_test = predict_quantiles(model, data["x_test"])

    # MC-dropout disagreement estimates quantile-regression epistemic uncertainty.
    qlo_cal_mc, qhi_cal_mc = predict_quantiles_mc(
        model,
        data["x_cal"],
        cfg.uacqr_mc_samples,
    )
    qlo_test_mc, qhi_test_mc = predict_quantiles_mc(
        model,
        data["x_test"],
        cfg.uacqr_mc_samples,
    )

    spread_lo_cal = np.maximum(
        np.std(qlo_cal_mc, axis=0, ddof=1).reshape(-1, 1),
        cfg.uacqr_spread_floor,
    )
    spread_hi_cal = np.maximum(
        np.std(qhi_cal_mc, axis=0, ddof=1).reshape(-1, 1),
        cfg.uacqr_spread_floor,
    )
    spread_lo_test = np.maximum(
        np.std(qlo_test_mc, axis=0, ddof=1).reshape(-1, 1),
        cfg.uacqr_spread_floor,
    )
    spread_hi_test = np.maximum(
        np.std(qhi_test_mc, axis=0, ddof=1).reshape(-1, 1),
        cfg.uacqr_spread_floor,
    )

    scores = np.maximum(
        (qlo_cal - data["y_cal_std"]) / spread_lo_cal,
        (data["y_cal_std"] - qhi_cal) / spread_hi_cal,
    )
    qhat = finite_sample_quantile(scores, cfg.alpha)

    lower_std = qlo_test - qhat * spread_lo_test
    upper_std = qhi_test + qhat * spread_hi_test
    lower_std, upper_std = order_interval(lower_std, upper_std)

    return (
        unstandardize_y(lower_std, data["y_mean"], data["y_scale"]),
        unstandardize_y(upper_std, data["y_mean"], data["y_scale"]),
    )


def mixture_normal_cdf(
    z: torch.Tensor,
    logit_samples: torch.Tensor,
    loc_samples: torch.Tensor,
    scale_samples: torch.Tensor,
) -> torch.Tensor:
    # z has shape [n]; model outputs have shape [M, n, K].
    standardized = (z.unsqueeze(0).unsqueeze(-1) - loc_samples) / scale_samples
    component_cdf = 0.5 * (
        1.0 + torch.erf(standardized / math.sqrt(2.0))
    )
    component_weights = torch.softmax(logit_samples, dim=-1)
    draw_cdf = torch.sum(component_weights * component_cdf, dim=-1)
    return torch.mean(draw_cdf, dim=0)


def invert_mixture_normal_cdf(
    target_probability: float,
    logit_samples: torch.Tensor,
    loc_samples: torch.Tensor,
    scale_samples: torch.Tensor,
    steps: int,
) -> np.ndarray:
    target = float(np.clip(target_probability, 1e-6, 1.0 - 1e-6))

    lower = torch.amin(loc_samples - 8.0 * scale_samples, dim=(0, 2))
    upper = torch.amax(loc_samples + 8.0 * scale_samples, dim=(0, 2))

    for _ in range(steps):
        midpoint = 0.5 * (lower + upper)
        cdf_mid = mixture_normal_cdf(
            midpoint,
            logit_samples,
            loc_samples,
            scale_samples,
        )
        lower = torch.where(cdf_mid < target, midpoint, lower)
        upper = torch.where(cdf_mid >= target, midpoint, upper)

    return to_numpy(0.5 * (lower + upper)).reshape(-1, 1)


def run_epicscore(
    hetero_model: HeteroMLP,
    data: Dict[str, np.ndarray],
    cfg: Config,
) -> Tuple[np.ndarray, np.ndarray]:
    # Base score: LACP standardized absolute residual.
    mu_cal, h2_cal, _ = predict_hetero(hetero_model, data["x_cal"])
    mu_test, h2_test, _ = predict_hetero(hetero_model, data["x_test"])

    h_cal = np.sqrt(np.maximum(h2_cal, cfg.variance_floor))
    h_test = np.sqrt(np.maximum(h2_test, cfg.variance_floor))
    base_scores = np.abs(data["y_cal_std"] - mu_cal) / h_cal

    # EPICSCORE uses one calibration subset to fit the predictive score CDF
    # and the other subset to conformalize the transformed score.
    idx = np.random.permutation(len(data["x_cal"]))
    n_fit = int(round(cfg.epic_fit_fraction * len(idx)))
    n_fit = min(max(n_fit, 10), len(idx) - 10)
    fit_idx = idx[:n_fit]
    conformal_idx = idx[n_fit:]

    log_scores_fit = np.log(
        base_scores[fit_idx] + cfg.epic_score_epsilon
    ).astype(np.float32)

    score_model = train_score_distribution_model(
        data["x_cal"][fit_idx],
        log_scores_fit,
        cfg,
    )

    logits_cal, loc_cal, scale_cal = predict_score_distribution_mc(
        score_model,
        data["x_cal"][conformal_idx],
        cfg.epic_mc_samples,
    )

    log_scores_conformal = torch.log(
        to_tensor(base_scores[conformal_idx].reshape(-1))
        + cfg.epic_score_epsilon
    )
    transformed_scores = mixture_normal_cdf(
        log_scores_conformal,
        logits_cal,
        loc_cal,
        scale_cal,
    )
    threshold_probability = finite_sample_quantile(
        to_numpy(transformed_scores),
        cfg.alpha,
    )

    logits_test, loc_test, scale_test = predict_score_distribution_mc(
        score_model,
        data["x_test"],
        cfg.epic_mc_samples,
    )
    log_score_threshold = invert_mixture_normal_cdf(
        threshold_probability,
        logits_test,
        loc_test,
        scale_test,
        cfg.epic_bisection_steps,
    )
    score_threshold = np.maximum(
        np.exp(log_score_threshold) - cfg.epic_score_epsilon,
        0.0,
    )

    lower_std = mu_test - score_threshold * h_test
    upper_std = mu_test + score_threshold * h_test

    del (
        score_model,
        logits_cal,
        loc_cal,
        scale_cal,
        logits_test,
        loc_test,
        scale_test,
    )
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    return (
        unstandardize_y(lower_std, data["y_mean"], data["y_scale"]),
        unstandardize_y(upper_std, data["y_mean"], data["y_scale"]),
    )


def run_lwcp(
    hetero_model: HeteroMLP,
    data: Dict[str, np.ndarray],
    cfg: Config,
) -> Tuple[np.ndarray, np.ndarray]:
    # Official LWCP form with the default weight w(h)=(1+h)^(-1/2),
    # using last-layer neural features for leverage.
    _, _, phi_train = predict_hetero(hetero_model, data["x_train"])
    mu_cal, _, phi_cal = predict_hetero(hetero_model, data["x_cal"])
    mu_test, _, phi_test = predict_hetero(hetero_model, data["x_test"])

    covariance = compute_unweighted_feature_covariance(
        phi_train,
        cfg.lwcp_ridge,
        cfg,
    )
    leverage_cal = quadratic_form(phi_cal, covariance)
    leverage_test = quadratic_form(phi_test, covariance)

    weight_cal = 1.0 / np.sqrt(1.0 + leverage_cal)
    weight_test = 1.0 / np.sqrt(1.0 + leverage_test)

    scores = np.abs(data["y_cal_std"] - mu_cal) * weight_cal
    qhat = finite_sample_quantile(scores, cfg.alpha)

    half_width_test = qhat / np.maximum(weight_test, 1e-8)
    lower_std = mu_test - half_width_test
    upper_std = mu_test + half_width_test

    return (
        unstandardize_y(lower_std, data["y_mean"], data["y_scale"]),
        unstandardize_y(upper_std, data["y_mean"], data["y_scale"]),
    )


def run_claps(
    hetero_model: HeteroMLP,
    data: Dict[str, np.ndarray],
    cfg: Config,
) -> Tuple[np.ndarray, np.ndarray]:
    chosen_lambda = choose_prior_precision(
        hetero_model,
        data["x_train"],
        data["y_train_std"],
        cfg,
    )

    _, h2_train, phi_train = predict_hetero(
        hetero_model,
        data["x_train"],
    )
    mu_cal, h2_cal, phi_cal = predict_hetero(
        hetero_model,
        data["x_cal"],
    )
    mu_test, h2_test, phi_test = predict_hetero(
        hetero_model,
        data["x_test"],
    )

    covariance = compute_weighted_laplace_covariance(
        phi_train,
        h2_train,
        chosen_lambda,
        cfg,
    )
    epi_cal = quadratic_form(phi_cal, covariance)
    epi_test = quadratic_form(phi_test, covariance)

    total_var_cal = np.maximum(h2_cal + epi_cal, cfg.variance_floor)
    total_var_test = np.maximum(h2_test + epi_test, cfg.variance_floor)

    scores = np.abs(data["y_cal_std"] - mu_cal) / np.sqrt(total_var_cal)
    qhat = finite_sample_quantile(scores, cfg.alpha)

    lower_std = mu_test - qhat * np.sqrt(total_var_test)
    upper_std = mu_test + qhat * np.sqrt(total_var_test)

    return (
        unstandardize_y(lower_std, data["y_mean"], data["y_scale"]),
        unstandardize_y(upper_std, data["y_mean"], data["y_scale"]),
    )


