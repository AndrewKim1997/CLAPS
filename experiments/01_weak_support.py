def compute_four_metrics(
    method_name: str,
    seed: int,
    y_test: np.ndarray,
    region_test: np.ndarray,
    lower: np.ndarray,
    upper: np.ndarray,
    cfg: Config,
) -> Dict[str, float]:
    y = y_test.reshape(-1)
    lower = lower.reshape(-1)
    upper = upper.reshape(-1)

    covered = (y >= lower) & (y <= upper)
    width = upper - lower
    score = interval_score(y, lower, upper, cfg.alpha)

    sparse_mask = region_test == REGION_SPARSE_LOW
    dense_low_mask = region_test == REGION_DENSE_LOW

    sparse_width = float(np.mean(width[sparse_mask]))
    dense_low_width = float(np.mean(width[dense_low_mask]))

    return {
        "method": method_name,
        "seed": seed,
        "marginal_coverage": float(np.mean(covered)),
        "sparse_coverage": float(np.mean(covered[sparse_mask])),
        "sparse_dense_width_ratio": sparse_width / max(dense_low_width, 1e-12),
        "interval_score": float(np.mean(score)),
    }


