def run_single_seed(seed: int, cfg: Config) -> List[Dict[str, float]]:
    set_seed(seed)
    data = make_dataset(cfg)

    mean_model = train_mean_model(
        data["x_train"],
        data["y_train_std"],
        cfg,
    )
    hetero_model = train_hetero_model(
        data["x_train"],
        data["y_train_std"],
        cfg,
    )
    quantile_model = train_quantile_model(
        data["x_train"],
        data["y_train_std"],
        cfg,
    )

    method_runners = [
        ("Split CP", lambda: run_split_cp(mean_model, data, cfg)),
        ("LACP", lambda: run_lacp(hetero_model, data, cfg)),
        ("CQR", lambda: run_cqr(quantile_model, data, cfg)),
        ("UACQR-S", lambda: run_uacqr_s(quantile_model, data, cfg)),
        ("EPICSCORE-MDN", lambda: run_epicscore(hetero_model, data, cfg)),
        ("LWCP", lambda: run_lwcp(hetero_model, data, cfg)),
        ("CLAPS", lambda: run_claps(hetero_model, data, cfg)),
        ("CV+", lambda: run_cv_plus(data, cfg, seed)),
    ]

    results = []
    for method_name, runner in method_runners:
        lower, upper = runner()
        results.append(
            compute_four_metrics(
                method_name,
                seed,
                data["y_test"],
                data["region_test"],
                lower,
                upper,
                cfg,
            )
        )

    del mean_model, hetero_model, quantile_model, data
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    return results


def run_experiment(cfg: Config) -> pd.DataFrame:
    all_results = []
    start_time = time.time()

    for seed in range(cfg.num_seeds):
        if cfg.verbose:
            elapsed = time.time() - start_time
            print(
                f"[{seed + 1}/{cfg.num_seeds}] "
                f"seed={seed} | elapsed={elapsed:.1f}s"
            )

        all_results.extend(run_single_seed(seed, cfg))

    return pd.DataFrame(all_results)


