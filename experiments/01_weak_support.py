def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def to_tensor(x: np.ndarray) -> torch.Tensor:
    return torch.tensor(x, dtype=torch.float32, device=DEVICE)


def to_numpy(x: torch.Tensor) -> np.ndarray:
    return x.detach().cpu().numpy()


def train_validation_split(
    n: int,
    validation_fraction: float,
) -> Tuple[np.ndarray, np.ndarray]:
    idx = np.random.permutation(n)
    n_val = max(1, int(round(n * validation_fraction)))
    return idx[n_val:], idx[:n_val]


def finite_sample_quantile(scores: np.ndarray, alpha: float) -> float:
    scores = np.asarray(scores, dtype=float).reshape(-1)
    scores = scores[np.isfinite(scores)]

    n = len(scores)
    if n == 0:
        return np.inf

    k = int(np.ceil((n + 1) * (1.0 - alpha)))
    if k > n:
        return np.inf

    return float(np.partition(scores, k - 1)[k - 1])


def lower_cv_quantile(
    values: np.ndarray,
    alpha: float,
) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    n = values.shape[0]
    if n == 0:
        raise ValueError("CV+ received no lower candidates.")

    k = int(np.floor((n + 1) * alpha))
    k = min(max(k, 1), n)
    return np.sort(values, axis=0)[k - 1, :]


def upper_cv_quantile(
    values: np.ndarray,
    alpha: float,
) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    n = values.shape[0]
    if n == 0:
        raise ValueError("CV+ received no upper candidates.")

    k = int(np.ceil((n + 1) * (1.0 - alpha)))
    k = min(max(k, 1), n)
    return np.sort(values, axis=0)[k - 1, :]


def interval_score(
    y: np.ndarray,
    lower: np.ndarray,
    upper: np.ndarray,
    alpha: float,
) -> np.ndarray:
    y = np.asarray(y).reshape(-1)
    lower = np.asarray(lower).reshape(-1)
    upper = np.asarray(upper).reshape(-1)

    width = upper - lower
    score = width.copy()

    below = y < lower
    above = y > upper

    score[below] += (2.0 / alpha) * (lower[below] - y[below])
    score[above] += (2.0 / alpha) * (y[above] - upper[above])

    return score


def unstandardize_y(
    y_std: np.ndarray,
    y_mean: float,
    y_scale: float,
) -> np.ndarray:
    return y_std * y_scale + y_mean


def order_interval(
    lower: np.ndarray,
    upper: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    return np.minimum(lower, upper), np.maximum(lower, upper)


