def predict_mean(model: MeanMLP, x: np.ndarray) -> np.ndarray:
    model.eval()
    with torch.no_grad():
        pred = model(to_tensor(x))
    return to_numpy(pred).reshape(-1, 1)


def predict_hetero(
    model: HeteroMLP,
    x: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    model.eval()
    with torch.no_grad():
        mu, h2, phi = model(to_tensor(x))
    return (
        to_numpy(mu).reshape(-1, 1),
        to_numpy(h2).reshape(-1, 1),
        to_numpy(phi),
    )


def predict_quantiles(
    model: QuantileDropoutMLP,
    x: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    model.eval()
    with torch.no_grad():
        qlo, qhi = model(to_tensor(x))
    return to_numpy(qlo).reshape(-1, 1), to_numpy(qhi).reshape(-1, 1)


def predict_quantiles_mc(
    model: QuantileDropoutMLP,
    x: np.ndarray,
    n_samples: int,
) -> Tuple[np.ndarray, np.ndarray]:
    x_t = to_tensor(x)
    lower_samples = []
    upper_samples = []

    # Train mode activates dropout; gradients remain disabled.
    model.train()
    with torch.no_grad():
        for _ in range(n_samples):
            qlo, qhi = model(x_t)
            lower_samples.append(to_numpy(qlo).reshape(-1))
            upper_samples.append(to_numpy(qhi).reshape(-1))
    model.eval()

    return np.stack(lower_samples, axis=0), np.stack(upper_samples, axis=0)


def predict_score_distribution_mc(
    model: ScoreDistributionMLP,
    x: np.ndarray,
    n_samples: int,
) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    x_t = to_tensor(x)
    logit_samples = []
    loc_samples = []
    scale_samples = []

    model.train()
    with torch.no_grad():
        for _ in range(n_samples):
            logits, loc, scale = model(x_t)
            logit_samples.append(logits)
            loc_samples.append(loc)
            scale_samples.append(scale)
    model.eval()

    return (
        torch.stack(logit_samples, dim=0),
        torch.stack(loc_samples, dim=0),
        torch.stack(scale_samples, dim=0),
    )


